#!/usr/bin/env bash
# Negative control for test_audio_recovery_e2e.sh: the same scenarios with the daemon's
# recovery code from a base commit (default 3e5ea234, coregate v2.1, deployed on a lab MiSTer on
# 10/4 and rolled back at gate 7). Each must FAIL there, for the reason the glass runs
# showed: the first play's audio Begin is not adopted, its Reset is not ACKed, the epoch is
# retained ("reset ownership retained; new play must recover this epoch"), and every later
# play stops on "prior epoch still owns an unacknowledged reset fence"; a killed owner's
# consumer is never reclaimed. Only the recovery code (BASE_FILES) comes from the base;
# everything else, incl. main.cpp (the lab --play-count flag) and the fixtures, comes from
# this tree, so later companion/main API changes (r3) still compile.
# Exit: 0 every scenario failed as on glass; 1 a scenario passed or failed another way; 3
# NEG_BUILD_FAIL, the base daemon did not build. review 06:58: fail closed. A base daemon that
# does not build proves nothing, so it is NEG_BUILD_FAIL with rc 3, never a pass and never the
# generic FAIL (rc 1). No stale binary may stand in for the build.
# MAST R5 rows (w9, review 01:10-01:28): with AUDIO_RECOVERY_BASE_REF=298a7a16 (the daemon glass
# G2 01:03 ran) reload_no_answer fails on 'no loud cure-failed line' (the G2 silence) and
# wedge_reload on R5f's commit check; bases without the hand-off fail both before any reload.
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
BASE=${AUDIO_RECOVERY_BASE_REF:-3e5ea234}
OUT=${AUDIO_RECOVERY_NEG_OUT:-$ROOT/build/audio_recovery_neg}
# w9's MAST-wedge rows (dev/w9-mast-wedge) join the default set wherever this tree's e2e
# defines them, so the control still runs unchanged on trees without those rows.
DEFAULT_SCENARIOS="reboot reboot_reject persistent killed midreset wedged"
for s in wedge_reload wedge_twice wedge_begin handoff_lost boot_race reload_no_answer; do
    if grep -q "^run_$s()" "$ROOT/tests/unit/test_audio_recovery_e2e.sh"; then
        DEFAULT_SCENARIOS+=" $s"
    fi
done
SCENARIOS=${AUDIO_RECOVERY_SCENARIOS:-$DEFAULT_SCENARIOS}
SRC=$OUT/src
rm -rf "$SRC"
mkdir -p "$SRC"
BASE_FILES=${AUDIO_RECOVERY_BASE_FILES:-arm/misterplexd/fpga_spi.cpp arm/misterplexd/fpga_spi.hpp arm/misterplexd/media_player.cpp}
git -C "$ROOT" ls-files -z arm/misterplexd host assets/plex-profiles | (cd "$ROOT" && xargs -0 cp --parents -t "$SRC")
# shellcheck disable=SC2086
git -C "$ROOT" archive "$BASE" $BASE_FILES | tar -x -C "$SRC"
# kPlx (3af5fcaf) made the PLX page offsets-only, so this tree no longer has the absolute 320-page
# names a pre-kPlx base's fpga_spi.hpp uses (mailbox_abi::kPlxkAddr, kDdrStatusMailboxPhys,
# kInputMailboxPhys). Give the base build copy exactly those, with the base's own values, and assert
# this tree's PLXS/PLXI offsets put them where the base had them. The shipped ABI is not touched.
if grep -q 'mailbox_abi::kPlxkAddr' "$SRC/arm/misterplexd/fpga_spi.hpp" &&
    ! grep -q 'kPlxkAddr *=' "$SRC/host/libmisterplex/mailbox_abi_spec.hpp"; then
    base_addr() {
        git -C "$ROOT" show "$BASE:host/libmisterplex/mailbox_abi_spec.hpp" |
            sed -n "s/^constexpr uint32_t $1 *= *\(0x[0-9A-Fa-f]*\)u;.*/\1/p"
    }
    plxk=$(base_addr kPlxkAddr) plxs=$(base_addr kPlxsAddr) plxi=$(base_addr kPlxiAddr)
    if [ -z "$plxk" ] || [ -z "$plxs" ] || [ -z "$plxi" ]; then
        echo "FAIL: base $BASE has no PLXK/PLXS/PLXI addresses for the pre-kPlx shim" >&2
        exit 1
    fi
    cat > "$SRC/arm/misterplexd/neg_base_abi_shim.hpp" <<EOF
#pragma once
// Generated by test_audio_recovery_negative.sh for the $BASE base build only.
#include <cstdint>
#include "libmisterplex/input_mailbox.hpp"
namespace mailbox_abi {
constexpr uint32_t kPlxkAddr = ${plxk}u;
}
namespace misterplex {
constexpr uint32_t kDdrStatusMailboxPhys = ${plxs}u;
constexpr uint32_t kInputMailboxPhys = ${plxi}u;
static_assert(mailbox_abi::kPlxkAddr + kDdrStatusMailboxOff == kDdrStatusMailboxPhys, "PLXS offset");
static_assert(mailbox_abi::kPlxkAddr + kInputMailboxOff == kInputMailboxPhys, "PLXI offset");
}
EOF
    sed -i 's|^#include "libmisterplex/input_mailbox.hpp"$|&\n#include "neg_base_abi_shim.hpp"|' \
        "$SRC/arm/misterplexd/fpga_spi.hpp"
    grep -q '^#include "neg_base_abi_shim.hpp"$' "$SRC/arm/misterplexd/fpga_spi.hpp" || {
        echo "FAIL: could not add the pre-kPlx shim to the base fpga_spi.hpp" >&2
        exit 1
    }
    echo "  base $BASE: pre-kPlx shim PLXK $plxk, PLXS $plxs, PLXI $plxi"
fi

# R1 asks more of the base recovery files than a pre-R1 base has (tests/unit/neg_r1_shim.py: the
# R1 PLX port members, fpgaThreadMain's PLAY generation, enableBrowseV2). Such a base gets them in
# its build copy only, as refusals that print NEG_SHIM_USED; any NEG_SHIM_USED fails the control.
if grep -q 'fpga_\.plxStore32(' "$SRC/arm/misterplexd/media_player.hpp" &&
    ! grep -q 'plxStore32(' "$SRC/arm/misterplexd/fpga_spi.hpp"; then
    git -C "$ROOT" show "$BASE:arm/misterplexd/media_player.hpp" > "$OUT/base_media_player.hpp"
    python3 "$ROOT/tests/unit/neg_r1_shim.py" "$SRC/arm/misterplexd" "$OUT/base_media_player.hpp" \
        "$ROOT/arm/misterplexd/media_player.cpp" "$BASE" || {
        echo "FAIL: could not add the R1 shim to the base build copy" >&2
        exit 1
    }
fi

# Every legitimate old-daemon wedge signature per scenario, one per line (review 21:31): the
# glass line first, then the epoch-retained variants and "audio never ran" (the first audio Begin
# not adopted). Any one may match; a scenario the old daemon PASSES still fails this control.
declare -A expect=(
    [reboot]="reboot: a later play hit 'prior epoch still owns'
reboot: an epoch was retained"
    [reboot_reject]="reboot_reject: a later play hit 'prior epoch still owns'
reboot_reject: an epoch was retained"
    [persistent]="persistent: a later play hit 'prior epoch still owns'
persistent: an epoch was retained"
    [killed]="the killed owner's session was not reclaimed
the first daemon's audio never ran"
    [midreset]="midreset: a later play hit 'prior epoch still owns'
midreset: an epoch was retained
play 1's audio never ran"
    [wedged]="play 1: the wedged lane was not reported
a wedged begin left an epoch owned
a wedged begin retained an epoch
no WEDGED gate-open MAST probe line"
    [wedge_reload]="no MAST reload hand-off at gate open
daemon 1 (exit 86): the audio command commit is 000000034d414343 after the exit, want 0 (R5f)"
    [wedge_twice]="no MAST reload hand-off at gate open"
    [wedge_begin]="no MAST reload hand-off at begin"
    [handoff_lost]="no MAST reload hand-off at gate open"
    [boot_race]="no guarded load ran"
    [reload_no_answer]="no guarded load ran
daemon 2: no loud cure-failed line within 90 s of its verified start"
)
rm -f "$OUT/run/misterplexd"
build=0
for s in $SCENARIOS; do
    out=$OUT/$s.out
    rc=0
    AUDIO_RECOVERY_DAEMON_SRC=$SRC AUDIO_RECOVERY_OUT=$OUT/run AUDIO_RECOVERY_SCENARIOS=$s \
        AUDIO_RECOVERY_REUSE_BUILD=$build "$ROOT/tests/unit/test_audio_recovery_e2e.sh" \
        > "$out" 2>&1 || rc=$?
    if [ "$build" = 0 ] && [ ! -x "$OUT/run/misterplexd" ]; then
        echo "NEG_BUILD_FAIL: the $BASE daemon (recovery code from $BASE, the rest from this tree)" \
            "did not build; the negative control proves nothing (rc 3):" >&2
        grep -m 5 -E 'error' "$out" >&2 || tail -n 20 "$out" >&2
        exit 3
    fi
    build=1
    used=$(grep -rIl 'NEG_SHIM_USED' "$OUT/run" "$out" 2>/dev/null || true)
    if [ -n "$used" ]; then
        echo "FAIL: scenario $s: the $BASE build reached the R1 shim (NEG_SHIM_USED in" \
            "$(echo $used)); the negative is not the base's behaviour" >&2
        grep -h -m 3 'NEG_SHIM_USED' $used >&2 || true
        exit 1
    fi
    if [ "$rc" = 0 ]; then
        echo "FAIL: scenario $s passed with the $BASE daemon" >&2
        exit 1
    fi
    matched=""
    while IFS= read -r sig; do
        if grep -qF "FAIL [$s]: $sig" "$out"; then matched=$sig; break; fi
    done <<< "${expect[$s]}"
    if [ -z "$matched" ]; then
        echo "FAIL: scenario $s failed with the $BASE daemon, but with no known old-daemon signature:" >&2
        printf '  accepted: %s\n' "${expect[$s]//$'\n'/ | }" >&2
        tail -n 20 "$out" >&2
        exit 1
    fi
    # Daemon logs of this scenario: one per daemon for multi-daemon rows ($s-1.log, $s-2.log),
    # boot_race in its own tree (w9; review 00:51 N1). Silent when none exists (early death).
    logs=("$OUT/run/$s.log" "$OUT/run/$s"-[0-9]*.log)
    if [ "$s" = boot_race ] || [ "$s" = reload_no_answer ]; then logs+=("$OUT/run/br/tmp/mpxd.log"); fi
    sig=""
    for line in 'audio session reset ACK failed' 'reset ownership retained' \
        'prior epoch still owns an unacknowledged reset fence' \
        'MrAudio lane wedged: no fresh MAST publication' 'FPGA begin attempt 5/5 failed'; do
        # grep -s: a missing log is silent; -q: any match wins even if another file is missing.
        if grep -qs "$line" "${logs[@]}"; then sig+=" '$line'"; fi
    done
    echo "  [$s] $BASE fails: $matched; daemon log:${sig:- (no recovery lines)}"
done
echo "test_audio_recovery_negative: OK ($BASE fails every scenario: $SCENARIOS)"
