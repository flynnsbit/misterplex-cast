#!/usr/bin/env python3
"""The R1 shim for test_audio_recovery_negative.sh: the base daemon's build copy only.

R1 (review 07:30 C1 3f962bcb, the R1 PLXH port db9da7c6, browse P1 e6cf24fa) asks more of the
base recovery files (fpga_spi.cpp/.hpp, media_player.cpp from the base) than a pre-R1 base has:
  - this tree's media_player.hpp FpgaSpiPlxPort calls FpgaSpi::plxStore32/plxStore64/plxLoad64;
  - its fpgaThreadMain carries the PLAY generation (a 6th parameter), which the base defines and
    calls with 5;
  - main.cpp links MediaPlayer::enableBrowseV2 (called only with MPX_BROWSE_V2=1).
In the build copy (SRC/arm/misterplexd) the base gets the three PLX members and enableBrowseV2 as
refusals that print NEG_SHIM_USED (neg_base_r1_shim.hpp), and its own fpgaThreadMain declared next
to the tree's. Each edit is anchored and must apply exactly once, else this exits 1. The shipped
files are not touched. The negative control fails (rc 1) on any NEG_SHIM_USED line.
Usage: neg_r1_shim.py SRC_ARM_DIR BASE_MEDIA_PLAYER_HPP TREE_MEDIA_PLAYER_CPP BASE_REF
"""
import re
import sys


def one(what, n):
    if n != 1:
        sys.exit(f"FAIL: R1 shim: {what} found {n} times, want 1")


def main():
    d, base_h, tree_cpp, base = sys.argv[1:5]
    with open(d + "/neg_base_r1_shim.hpp", "w") as out:
        out.write(
            "#pragma once\n"
            f"// Generated by test_audio_recovery_negative.sh for the {base} base build only (R1 shim).\n"
            "#include <cstdio>\n"
            "namespace neg_shim {\n"
            "inline bool used(const char* what) {\n"
            f"    std::fprintf(stderr, \"NEG_SHIM_USED %s: the {base} base build reached R1 code\\n\", what);\n"
            "    std::fflush(stderr);\n"
            "    return false;\n"
            "}\n"
            "#ifdef NEG_SHIM_SELFTEST\n"
            "inline const bool selftest = used(\"selftest\");\n"
            "#endif\n"
            "}\n")

    f = open(d + "/fpga_spi.hpp").read()
    inc = '#include "libmisterplex/input_mailbox.hpp"\n'
    cls = "class FpgaSpi {\npublic:\n"
    one("the base fpga_spi.hpp input_mailbox include", f.count(inc))
    one("the base 'class FpgaSpi {' + 'public:'", f.count(cls))
    members = "".join(
        f"    bool {name}({args}) {{ return neg_shim::used(\"{name}\"); }}\n"
        for name, args in (("plxStore32", "uint32_t, uint32_t"), ("plxStore64", "uint32_t, uint64_t"),
                           ("plxLoad64", "uint32_t, uint64_t*")))
    f = f.replace(inc, inc + '#include "neg_base_r1_shim.hpp"\n', 1).replace(cls, cls + members, 1)
    open(d + "/fpga_spi.hpp", "w").write(f)
    done = ["FpgaSpi plxStore32/plxStore64/plxLoad64 refuse"]

    decl = re.compile(r"^    void fpgaThreadMain\([^;]*\);\n", re.M)
    h = open(d + "/media_player.hpp").read()
    tree_decl, base_decl = decl.findall(h), decl.findall(open(base_h).read())
    one("this tree's fpgaThreadMain declaration", len(tree_decl))
    one("the base's fpgaThreadMain declaration", len(base_decl))
    if tree_decl[0] != base_decl[0]:
        open(d + "/media_player.hpp", "w").write(h.replace(tree_decl[0], tree_decl[0] + base_decl[0], 1))
        done.append("the base fpgaThreadMain declared too")

    main_cpp = open(d + "/main.cpp").read()
    c = open(d + "/media_player.cpp").read()
    if ".enableBrowseV2(" in main_cpp and "MediaPlayer::enableBrowseV2(" not in c:
        sig = re.findall(r"^void MediaPlayer::enableBrowseV2\([^{;]*\) \{$", open(tree_cpp).read(), re.M)
        one("this tree's MediaPlayer::enableBrowseV2 definition", len(sig))
        c += ("\nnamespace misterplex {\n// The R1 shim (test_audio_recovery_negative.sh): MPX_BROWSE_V2=1 only.\n"
              + sig[0] + "\n    neg_shim::used(\"enableBrowseV2\");\n}\n}  // namespace misterplex\n")
        open(d + "/media_player.cpp", "w").write(c)
        done.append("enableBrowseV2 refuses")
    print(f"  base {base}: R1 shim: " + "; ".join(done) + " (NEG_SHIM_USED fails the control)")


if __name__ == "__main__":
    main()
