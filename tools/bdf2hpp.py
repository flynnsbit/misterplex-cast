#!/usr/bin/env python3
"""Generate the MiSTerPlex Spleen 8x16 glyph table.

The output is deterministic: no timestamps, host paths, or locale-dependent
sorting are emitted.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path


TAG = "2.2.0"
COMMIT = "0493c34e22791824767c618fed42c434b477662c"
EXPECTED_SHA256 = "4a3d97ee61a8c86a7525d8c723cb8a14081f395cd2feb4227ba5e3baf0629bae"


def load_bdf(path: Path) -> list[list[int]]:
    glyphs: dict[int, list[int]] = {}
    enc: int | None = None
    bbx: tuple[int, int, int, int] | None = None
    rows: list[int] = []
    in_bitmap = False

    for line in path.read_text(encoding="latin-1").splitlines():
        parts = line.split()
        if not parts:
            continue
        if parts[0] == "ENCODING":
            enc = int(parts[1])
        elif parts[0] == "BBX":
            bbx = tuple(int(v) for v in parts[1:5])  # type: ignore[assignment]
        elif parts[0] == "BITMAP":
            in_bitmap = True
            rows = []
        elif parts[0] == "ENDCHAR":
            in_bitmap = False
            if enc is not None and 0x20 <= enc <= 0x7E:
                if bbx is None:
                    raise ValueError(f"glyph {enc} has no BBX")
                width, height, xoff, yoff = bbx
                if width != 8 or height != 16 or xoff != 0 or yoff != -4:
                    raise ValueError(f"glyph {enc} BBX {bbx} is not 8x16+0-4")
                cell = [0] * 16
                top = 16 - 4 - (height + yoff)
                for i, row in enumerate(rows):
                    y = top + i
                    if 0 <= y < 16:
                        cell[y] = row & 0xFF
                glyphs[enc] = cell
            enc = None
            bbx = None
            rows = []
        elif in_bitmap:
            value = int(parts[0], 16)
            if len(parts[0]) > 2:
                value >>= len(parts[0]) * 4 - 8
            rows.append(value)

    missing = [c for c in range(0x20, 0x7F) if c not in glyphs]
    if missing:
        raise ValueError("missing glyphs: " + ", ".join(hex(c) for c in missing))
    return [glyphs[c] for c in range(0x20, 0x7F)]


def generate(bdf: Path, license_path: Path) -> str:
    bdf_bytes = bdf.read_bytes()
    sha = hashlib.sha256(bdf_bytes).hexdigest()
    if sha != EXPECTED_SHA256:
        raise ValueError(f"{bdf} sha256 {sha} != expected {EXPECTED_SHA256}")
    license_text = license_path.read_text(encoding="utf-8").rstrip()
    glyphs = load_bdf(bdf)

    out: list[str] = []
    out.append("// This file is generated by tools/bdf2hpp.py; do not edit by hand.")
    out.append("//")
    out.append("// Spleen 8x16 by Frederic Cambus, BSD-2-Clause.")
    out.append(f"// Upstream tag: {TAG}")
    out.append(f"// Upstream commit: {COMMIT}")
    out.append(f"// BDF sha256: {sha}")
    out.append("//")
    for line in license_text.splitlines():
        out.append("//" if not line else "// " + line)
    out.append("#pragma once")
    out.append("")
    out.append("#include <array>")
    out.append("#include <cstdint>")
    out.append("")
    out.append("namespace misterplex {")
    out.append("inline constexpr int kFont8x16First = 0x20;")
    out.append("inline constexpr int kFont8x16Last = 0x7E;")
    out.append("inline constexpr int kFont8x16GlyphCount = 95;")
    out.append("inline constexpr int kFont8x16Rows = 16;")
    out.append("inline constexpr std::array<std::array<std::uint8_t, 16>, 95> kFont8x16 = {{")
    for code, rows in zip(range(0x20, 0x7F), glyphs):
        ch = chr(code)
        label = ch if ch not in {"\\", "'"} else "\\" + ch
        out.append(f"    /* 0x{code:02X} '{label}' */ {{ " + ", ".join(f"0x{v:02X}" for v in rows) + " },")
    out.append("}};")
    out.append("} // namespace misterplex")
    out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--bdf", required=True, type=Path)
    ap.add_argument("--license", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(generate(args.bdf, args.license), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
